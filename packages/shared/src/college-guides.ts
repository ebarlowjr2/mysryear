/**
 * College Readiness Hub — canonical guide content model.
 *
 * This is the single source of truth for the public Resources Hub on web
 * (`apps/web/src/app/resources`) and the mobile Resources screen
 * (`apps/mobile/app/resources`). Both platforms consume the SAME data from
 * here so content never drifts between surfaces.
 *
 * Content policy:
 *  - Plain-language, original MySRYear summaries — never long quotes from sources.
 *  - Inclusive language only (no gendered "son/daughter/he/she").
 *  - No hardcoded volatile facts (interest rates, award limits, application or
 *    test dates). Guides that touch changing facts set `volatileInformation`,
 *    carry at least one authoritative `officialSources` entry, and a
 *    `lastReviewedAt` date so readers always confirm current numbers at the
 *    official source.
 */

