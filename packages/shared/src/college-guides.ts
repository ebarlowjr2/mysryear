// ─────────────────────────── Query helpers ───────────────────────────

export type GuideFilter = {
  query?: string
  audience?: GuideAudience
  stage?: GuideStage
  category?: GuideCategorySlug
  timing?: GuideTiming
}

const CATEGORY_TITLE_BY_SLUG: Record<GuideCategorySlug, string> = GUIDE_CATEGORIES.reduce(
  (acc, category) => {
    acc[category.slug] = category.title
    return acc
  },
  {} as Record<GuideCategorySlug, string>,
)

export function getGuideCategory(slug: GuideCategorySlug): GuideCategory | undefined {
  return GUIDE_CATEGORIES.find((category) => category.slug === slug)
}

export function getGuideBySlug(slug: string): CollegeGuide | undefined {
  return COLLEGE_GUIDES.find((item) => item.slug === slug)
}

export function getGuidesByCategory(category: GuideCategorySlug): CollegeGuide[] {
  return COLLEGE_GUIDES.filter((item) => item.category === category)
}

export function getRelatedGuides(slug: string): CollegeGuide[] {
  const guideRecord = getGuideBySlug(slug)
  if (!guideRecord) return []
  return guideRecord.relatedGuideSlugs
    .map((relatedSlug) => getGuideBySlug(relatedSlug))
    .filter((item): item is CollegeGuide => Boolean(item))
}

function guideHaystack(item: CollegeGuide): string {
  return [
    item.title,
    item.shortSummary,
    item.whyItMatters,
    CATEGORY_TITLE_BY_SLUG[item.category],
    item.keywords.join(' '),
    item.actionSteps.join(' '),
  ]
    .join(' ')
    .toLowerCase()
}

export function searchGuides(query: string, guides: CollegeGuide[] = COLLEGE_GUIDES): CollegeGuide[] {
  const tokens = query.trim().toLowerCase().split(/\s+/).filter(Boolean)
  if (tokens.length === 0) return [...guides]
  return guides.filter((item) => {
    const haystack = guideHaystack(item)
    return tokens.every((token) => haystack.includes(token))
  })
}

export function filterGuides(filter: GuideFilter, guides: CollegeGuide[] = COLLEGE_GUIDES): CollegeGuide[] {
  let result = [...guides]
  if (filter.category) result = result.filter((item) => item.category === filter.category)
  if (filter.audience) result = result.filter((item) => item.audiences.includes(filter.audience as GuideAudience))
  if (filter.stage) result = result.filter((item) => item.gradesOrStages.includes(filter.stage as GuideStage))
  if (filter.timing) result = result.filter((item) => item.timing === filter.timing)
  if (filter.query && filter.query.trim()) result = searchGuides(filter.query, result)
  return result
}

/** Grade/stage-aware "Start Here" selection: a small, ordered set of guides most
 *  relevant to a given stage, used by the hub's Start Here path. */
export function startHereForStage(stage: GuideStage, limit = 4): CollegeGuide[] {
  const inStage = COLLEGE_GUIDES.filter((item) => item.gradesOrStages.includes(stage))
  return inStage.slice(0, limit)
}
